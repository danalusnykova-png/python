from pathlib import Path

# Зчитування тексту з файлу
шлях = Path(__file__).with_name("вхідні_дані.txt")

with open(шлях, "r", encoding="utf-8") as файл:
    текст = файл.read().lower()

# Розділення тексту на слова
слова = текст.split()
частота = {}

# Підрахунок повторень кожного слова
for слово in слова:
    слово = слово.strip(".,!?;:")

    if слово:
        частота[слово] = частота.get(слово, 0) + 1

# Виведення слів за алфавітом
print("Частота слів за алфавітом:")
for слово in sorted(частота):
    print(слово, "-", частота[слово])

# Сортування за кількістю повторень
print("\nСортування за частотою:")
for слово, кількість in sorted(
    частота.items(),
    key=lambda елемент: (-елемент[1], елемент[0])
):
    print(слово, "-", кількість)

# Створення словника слів, які повторюються
повторення = {
    слово: кількість
    for слово, кількість in частота.items()
    if кількість >= 2
}

print("\nСлова, які повторюються:")
print(повторення)

# Перевірка слова, якого немає у тексті
print("\nЧастота відсутнього слова:")
print(частота.get("пароль", 0))
