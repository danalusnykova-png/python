from abc import ABC, abstractmethod


# Абстрактний клас
class Доставка(ABC):

    @property
    @abstractmethod
    def назва(self):
        pass

    @abstractmethod
    def вартість(self, вага):
        pass

    @abstractmethod
    def термін(self):
        pass

    # Звичайний метод
    def інформація(self):
        return f"Спосіб доставки: {self.назва}"


# Поштова доставка
class ПоштоваДоставка(Доставка):

    @property
    def назва(self):
        return "Поштова доставка"

    def вартість(self, вага):
        return 50 + вага * 10

    def термін(self):
        return 3


# Кур'єрська доставка
class КурєрськаДоставка(Доставка):

    @property
    def назва(self):
        return "Кур'єрська доставка"

    def вартість(self, вага):
        return 100 + вага * 20

    def термін(self):
        return 1


# Клас для повідомлень
class Повідомлення:

    def надіслати(self, текст):
        print("Повідомлення:", текст)


# Клас замовлення
class Замовлення:

    def __init__(self, номер, вага, доставка, повідомлення):
        self.номер = номер
        self.вага = вага
        self.доставка = доставка
        self.повідомлення = повідомлення

    def оформити(self):
        print("Замовлення №", self.номер)
        print(self.доставка.інформація())
        print("Вартість:", self.доставка.вартість(self.вага), "грн")
        print("Термін:", self.доставка.термін(), "дн.")

        self.повідомлення.надіслати(
            f"Замовлення №{self.номер} оформлено"
        )


