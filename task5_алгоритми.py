import timeit
from statistics import mean

# Функція для вимірювання часу пошуку
def час_пошуку(структура):
    виміри = timeit.repeat(
        lambda: -1 in структура,
        repeat=5,
        number=10000
    )
    return mean(виміри) / 10000 * 1000000


# Отримання унікальних значень через список
def унікальні_список(дані):
    результат = []
    for число in дані:
        if число not in результат:
            результат.append(число)
    return результат


# Отримання унікальних значень через множину
def унікальні_множина(дані):
    результат = set()
    for число in дані:
        результат.add(число)
    return результат


# Функція вимірювання часу створення
def час_створення(функція, дані):
    виміри = timeit.repeat(
        lambda: функція(дані),
        repeat=5,
        number=1
    )
    return mean(виміри) * 1000


# Розміри наборів даних
розміри = [100, 1000, 10000]

print("ПОРІВНЯННЯ ШВИДКОСТІ СТРУКТУР ДАНИХ")
print()
print("Час пошуку - мкс, унікальні значення - мс")
print()

print(f"{'n':<8}{'list':<12}{'set':<12}"
      f"{'dict':<12}{'унік.list':<14}{'унік.set':<12}")

print("-" * 70)

for n in розміри:
    дані = [i // 2 for i in range(n)]

    список = list(дані)
    множина = set(дані)
    словник = dict.fromkeys(дані)

    t_list = час_пошуку(список)
    t_set = час_пошуку(множина)
    t_dict = час_пошуку(словник)

    t_unique_list = час_створення(
        унікальні_список, дані
    )

    t_unique_set = час_створення(
        унікальні_множина, дані
    )

    print(f"{n:<8}{t_list:<12.3f}"
          f"{t_set:<12.3f}"
          f"{t_dict:<12.3f}"
          f"{t_unique_list:<14.3f}"
          f"{t_unique_set:<12.3f}")

