# Базовий клас
class МережевийПристрій:
    def __init__(self, назва, ip):
        self.назва = назва
        self.ip = ip

    def робота(self):
        return "Пристрій працює в мережі"

    def __str__(self):
        return f"{self.назва}, IP: {self.ip}"


# Клас маршрутизатора
class Маршрутизатор(МережевийПристрій):
    def __init__(self, назва, ip, мережі):
        super().__init__(назва, ip)
        self.мережі = мережі

    def робота(self):
        return f"Передає дані між {self.мережі} мережами"


# Клас комутатора
class Комутатор(МережевийПристрій):
    def __init__(self, назва, ip, порти, активні):
        super().__init__(назва, ip)
        self.порти = порти
        self.активні = активні

    def робота(self):
        вільні = self.порти - self.активні
        return f"Активних портів: {self.активні}, вільних: {вільні}"


# Клас сервера
class Сервер(МережевийПристрій):
    def __init__(self, назва, ip, служба):
        super().__init__(назва, ip)
        self.служба = служба

    def робота(self):
        return f"Надає мережеву службу {self.служба}"


# Створення об'єктів
пристрої = [
    Маршрутизатор("Router", "192.168.1.1", 3),
    Комутатор("Switch", "192.168.1.2", 24, 10),
    Сервер("Server", "192.168.1.10", "DNS")
]

# Демонстрація поліморфізму
print("МЕРЕЖЕВІ ПРИСТРОЇ\n")

for пристрій in пристрої:
    print(пристрій)
    print("Робота:", пристрій.робота())
    print()

# Перевірка наслідування
print("ПЕРЕВІРКА ТИПІВ")
print("isinstance:", isinstance(пристрої[0], МережевийПристрій))
print("issubclass:", issubclass(Сервер, МережевийПристрій))
