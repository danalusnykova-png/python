# Базовий клас стратегії
class СпосібОцінювання:
    def розрахувати(self, оцінки):
        raise NotImplementedError("Метод потрібно реалізувати")


# Перша стратегія - середня оцінка
class СередняОцінка(СпосібОцінювання):
    def розрахувати(self, оцінки):
        return round(sum(оцінки) / len(оцінки), 2)


# Друга стратегія - без найнижчої оцінки
class БезНайнижчої(СпосібОцінювання):
    def розрахувати(self, оцінки):
        нові_оцінки = оцінки.copy()
        нові_оцінки.remove(min(нові_оцінки))
        return round(sum(нові_оцінки) / len(нові_оцінки), 2)


# Клас електронного журналу
class ЖурналОцінок:
    def __init__(self, предмет, оцінки, стратегія):
        self.предмет = предмет
        self.оцінки = оцінки
        self.стратегія = стратегія

    def змінити_стратегію(self, стратегія):
        self.стратегія = стратегія

    def підсумкова_оцінка(self):
        return self.стратегія.розрахувати(self.оцінки)


# Створення журналу
журнал = ЖурналОцінок(
    "Програмування",
    [70, 85, 95],
    СередняОцінка()
)

print("ЕЛЕКТРОННИЙ ЖУРНАЛ")
print("Предмет:", журнал.предмет)
print("Оцінки:", журнал.оцінки)

# Використання першої стратегії
print("\nСередня оцінка:")
print(журнал.підсумкова_оцінка())

# Використання другої стратегії
журнал.змінити_стратегію(БезНайнижчої())

print("\nОцінка без найнижчого балу:")
print(журнал.підсумкова_оцінка())


# Нова стратегія - додаткові бали
class ДодатковіБали(СпосібОцінювання):
    def розрахувати(self, оцінки):
        середня = sum(оцінки) / len(оцінки)
        return round(min(середня + 5, 100), 2)


# Додавання нової стратегії
журнал.змінити_стратегію(ДодатковіБали())

print("\nОцінка з додатковими балами:")
print(журнал.підсумкова_оцінка())
