# Клас датчика температури
class ДатчикТемператури:
    def __init__(self, назва, температура, поріг):
        self._назва = назва
        self._поріг = поріг
        self.температура = температура

    # Отримання температури
    @property
    def температура(self):
        return self.__температура

    # Перевірка та зміна температури
    @температура.setter
    def температура(self, значення):
        if type(значення) not in (int, float):
            raise TypeError("Температура повинна бути числом")

        if значення < -50 or значення > 100:
            raise ValueError("Температура має бути від -50 до 100")

        self.__температура = значення

    # Обчислювана властивість
    @property
    def стан(self):
        if self.температура > self._поріг:
            return "Перегрів"
        return "Норма"


# Створення об'єкта
датчик = ДатчикТемператури("Серверна кімната", 25, 30)

print("Назва:", датчик._назва)
print("Температура:", датчик.температура)
print("Стан:", датчик.стан)

# Зміна температури
датчик.температура = 40

print("\nПісля зміни температури:")
print("Температура:", датчик.температура)
print("Стан:", датчик.стан)

# Перевірка неправильного типу
try:
    датчик.температура = "висока"
except TypeError as помилка:
    print("\nПомилка типу:", помилка)

# Перевірка неправильного значення
try:
    датчик.температура = 150
except ValueError as помилка:
    print("Помилка значення:", помилка)

# Прямий доступ до приватного атрибута
try:
    print(датчик.__температура)
except AttributeError:
    print("Прямий доступ до приватного атрибута заборонено")

# Доступ через name mangling
print("Доступ через name mangling:",
      датчик._ДатчикТемператури__температура)
