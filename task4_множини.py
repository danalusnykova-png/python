# Початкові колекції чисел
список_1 = [101, 102, 102, 103, 104]
список_2 = [103, 104, 105, 105, 106]

print("Початковий список 1:", список_1)
print("Початковий список 2:", список_2)

# Створення множин без повторів
множина_1 = set(список_1)
множина_2 = set(список_2)

print("\nУнікальні значення:")
print("Множина 1:", sorted(множина_1))
print("Множина 2:", sorted(множина_2))

# Операції над множинами
print("\nОперації над множинами:")

print("Перетин:", sorted(множина_1 & множина_2))

print("Об'єднання:", sorted(множина_1 | множина_2))

print("Симетрична різниця:",
      sorted(множина_1 ^ множина_2))

# Перевірка підмножин
множина_3 = {101, 102}

print("\nПеревірка підмножин:")

print("Множина 3 є підмножиною множини 1:",
      множина_3 <= множина_1)

print("Множина 2 є підмножиною множини 1:",
      множина_2 <= множина_1)
